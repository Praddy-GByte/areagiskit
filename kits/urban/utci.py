"""Universal Thermal Climate Index (UTCI): the 6th-order polynomial approximation of Bröde et al. (2012), 210 terms,
and a mean radiant temperature (MRT) for a person standing in the open, from hourly radiation (NASA POWER).

UTCI = f(Ta, va, Tmrt - Ta, pa) with Ta air temperature (°C), va wind speed at 10 m (m/s, 0.5-17), pa vapour pressure
(kPa). The coefficients are those of the official UTCI Fortran code (www.utci.org), as also used by the pythermalcomfort
package (MIT); this module reproduces pythermalcomfort's polynomial to 1e-11 °C (checked in tests/test_social_access.py).

MRT follows the ERA5-HEAT approach (Di Napoli et al. 2020): a standing person (projected-area factor fp from the solar
elevation, Fanger 1970) absorbs direct, diffuse and ground-reflected short-wave radiation (absorptivity 0.7) and
long-wave radiation from sky and ground (emissivity 0.97). Ground long-wave is taken at air temperature and ground
albedo is 0.2: a simple, documented model for open ground in the sun, not for shaded streets.
"""

