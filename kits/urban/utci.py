_E = np.array([t[:4] for t in _TERMS], int)
_C = np.array([t[4] for t in _TERMS], float)

SIGMA = 5.670374e-8
CLASSES = [(46, "Extreme heat stress"), (38, "Very strong heat stress"), (32, "Strong heat stress"),
           (26, "Moderate heat stress"), (9, "No thermal stress")]


def _svp_hpa(t_c):
    """Saturation vapour pressure over water (hPa), the Hardy (1998) ITS-90 formula used in the UTCI code."""
    g = [-2836.5744, -6028.076559, 19.54263612, -0.02737830188, 0.000016261698, 7.0229056e-10, -1.8680009e-13]
    tk = np.asarray(t_c, float) + 273.15
    es = 2.7150305 * np.log(tk)
    for i, gi in enumerate(g):
        es = es + gi * tk ** (i - 2)
    return np.exp(es) * 0.01


def utci(ta, tmrt, va10, rh):
    """UTCI (°C). Inputs outside the polynomial's validity (Ta -50..50, Tmrt-Ta -30..70, va 0.5..17) are clipped."""
    ta = np.asarray(ta, float)
    d = np.clip(np.asarray(tmrt, float) - ta, -30.0, 70.0)
    v = np.clip(np.asarray(va10, float), 0.5, 17.0)
    pa = _svp_hpa(ta) * np.asarray(rh, float) / 100.0 / 10.0          # kPa
    t = np.clip(ta, -50.0, 50.0)
    out = np.zeros(np.broadcast(t, v, d, pa).shape, float)
    for (a, b, c, e), k in zip(_E, _C):
        out = out + k * t ** a * v ** b * d ** c * pa ** e
    return out


def solar_elevation(lat, doy, solar_hour):
    """Solar elevation (degrees) for local solar time (NASA POWER hourly data are in local solar time)."""
    decl = 23.45 * math.sin(math.radians(360.0 * (284 + doy) / 365.0))
    h = 15.0 * (solar_hour - 12.0)
    s = (math.sin(math.radians(lat)) * math.sin(math.radians(decl))
         + math.cos(math.radians(lat)) * math.cos(math.radians(decl)) * math.cos(math.radians(h)))
    return math.degrees(math.asin(max(-1.0, min(1.0, s))))


def mrt(ta, dni, dif, ghi, lw_down, elev_deg, albedo=0.2, a_sw=0.7, e_p=0.97):
    """Mean radiant temperature (°C) of a standing person in the open (Di Napoli et al. 2020, eq. 1-2)."""
    ta = np.asarray(ta, float)
    h = np.clip(np.asarray(elev_deg, float), 0.0, 90.0)
    fp = 0.308 * np.cos(np.radians(h * (1.0 - h ** 2 / 48402.0)))      # projected area factor (Fanger)
    fp = np.where(np.asarray(elev_deg) > 0, fp, 0.0)
    lw_up = SIGMA * (ta + 273.15) ** 4                                 # ground at air temperature
    sw = 0.5 * np.asarray(dif, float) + 0.5 * albedo * np.asarray(ghi, float) + fp * np.asarray(dni, float)
    s = 0.5 * np.asarray(lw_down, float) + 0.5 * lw_up + (a_sw / e_p) * sw
    return (s / SIGMA) ** 0.25 - 273.15


def stress_hours(u):
    u = np.asarray(u, float)
    return {"extreme": int((u >= 46).sum()), "very_strong": int(((u >= 38) & (u < 46)).sum()),
            "strong": int(((u >= 32) & (u < 38)).sum()), "moderate": int(((u >= 26) & (u < 32)).sum())}
